// Speeds up + eases the Android screen slide (`animation: "slide_from_right"`).
//
// react-native-screens drives that slide with its own anim resources
// (rns_slide_*), hard-coded to config_mediumAnimTime (400ms) with no
// interpolator — there's no prop for either. Android resource merging gives
// the app module priority over libraries, so writing files with the SAME
// names into the app's res/anim overrides them. Doing it from a config plugin
// keeps it working across `expo prebuild` (the android/ dir is generated).
//
// iOS is unaffected: there `slide_from_right` is the system push animation.
const fs = require("fs");
const path = require("path");
const { withDangerousMod } = require("expo/config-plugins");

const DURATION_MS = 250;
const INTERPOLATOR = "@android:interpolator/fast_out_slow_in";

// name -> [fromXDelta, toXDelta]. Push uses in_from_right + out_to_left; pop
// uses in_from_left + out_to_right (see react-native-screens'
// FragmentTransactionKt), so all four are overridden to keep them in sync.
const SLIDES = {
  rns_slide_in_from_right: ["100%", "0%"],
  rns_slide_out_to_left: ["0%", "-100%"],
  rns_slide_in_from_left: ["-100%", "0%"],
  rns_slide_out_to_right: ["0%", "100%"],
};

function slideXml(from, to) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withFastScreenTransitions.js — do not edit. -->
<translate xmlns:android="http://schemas.android.com/apk/res/android"
    android:duration="${DURATION_MS}"
    android:interpolator="${INTERPOLATOR}"
    android:fromXDelta="${from}"
    android:toXDelta="${to}" />
`;
}

module.exports = function withFastScreenTransitions(config) {
  return withDangerousMod(config, [
    "android",
    async (cfg) => {
      const animDir = path.join(
        cfg.modRequest.platformProjectRoot,
        "app/src/main/res/anim",
      );
      fs.mkdirSync(animDir, { recursive: true });
      for (const [name, [from, to]] of Object.entries(SLIDES)) {
        fs.writeFileSync(path.join(animDir, `${name}.xml`), slideXml(from, to));
      }
      return cfg;
    },
  ]);
};
